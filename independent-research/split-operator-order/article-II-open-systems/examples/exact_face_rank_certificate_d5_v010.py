def main():
    fs = traceless_hermitian_basis(5)
    blocks = []
    for ou, ov in OPS:
        u, v = from_ops(5, ou), from_ops(5, ov)
        blocks.append(measurement_block(engineered_square(u, v), fs))
    M = np.vstack(blocks)
    rank = rank_mod(M)
    print(f"prime={P} shape={M.shape[0]}x{M.shape[1]} rank={rank}")
    assert M.shape == (600, 576)
    assert rank == 576
    print("CERTIFIED_FULL_COLUMN_RANK_OVER_Q")


if __name__ == '__main__':
    main()
